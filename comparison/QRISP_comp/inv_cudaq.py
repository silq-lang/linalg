"""CUDA-Q Algorithms' official-example QSVT matrix-inversion workflow.

The CKS inverse approximation and QSPPACK preprocessing are taken from
NVIDIA's ``07_matrix_inversion_qsvt.py`` example at the pinned repository
commit. The quantum circuit is generated by the public ``QSVT.kernel`` API.
"""

from __future__ import annotations

import contextlib
import io

import cudaq
import numpy as np
from numpy.polynomial import chebyshev
from scipy.special import comb

from cudaq_algorithms import PauliLCU, PhaseSequence, QSVT


USE_TRACE_EXPORT = True
EPSILON = 2e-2
ENCODING = PauliLCU([(1.0, "I"), (-1.0 / 3.0, "X")])
# Eigenvalues of A/alpha are 1/2 and 1 for this benchmark.
X_MIN = 0.5


def inverse_chebyshev_coeffs(degree_half: int) -> np.ndarray:
    """NVIDIA example's exact CKS odd-Chebyshev coefficients."""
    coefficients = np.zeros(degree_half)
    for j in range(degree_half):
        tail = sum(
            comb(2 * degree_half, degree_half + i, exact=True)
            for i in range(j + 1, degree_half + 1)
        )
        coefficients[j] = (
            4 * ((-1) ** j) * tail / (2.0 ** (2 * degree_half))
        )
    return coefficients


def evaluate_odd(coefficients: np.ndarray, x: np.ndarray) -> np.ndarray:
    value = np.zeros_like(x, dtype=float)
    for j, coefficient in enumerate(coefficients):
        basis = np.zeros(2 * j + 2)
        basis[2 * j + 1] = 1.0
        value += coefficient * chebyshev.chebval(x, basis)
    return value


def inverse_phase_sequence(x_min: float, epsilon: float):
    """NVIDIA example's scaled CKS inverse and QSPPACK solve."""
    import qsppack

    degree_half = max(int(np.ceil(np.log(1 / epsilon) / x_min**2)), 3)
    coefficients = inverse_chebyshev_coeffs(degree_half)
    grid = np.linspace(-1, 1, 4000)
    scale = 0.9 / np.max(np.abs(evaluate_odd(coefficients, grid)))
    coefficients = coefficients * scale
    options = {
        "criteria": 1e-8,
        "method": "Newton",
        "typePhi": "full",
        "useReal": True,
        "targetPre": True,
    }
    with contextlib.redirect_stdout(io.StringIO()):
        phases, _ = qsppack.solve(coefficients.copy(), 1, options)
    return tuple(float(value) for value in phases), float(scale), degree_half


PHASES, SCALE, DEGREE_HALF = inverse_phase_sequence(X_MIN, EPSILON)


@cudaq.kernel
def prepare_rhs(state: cudaq.qview):
    x(state[0])


def build_kernel():
    return QSVT(ENCODING).kernel(
        PhaseSequence(PHASES, convention="qsp"), state_prep=prepare_rhs
    )


def trace_angles():
    prepare_angles = ENCODING.kernel_args[0]
    return (
        *(2.0 * value for value in PHASES),
        *prepare_angles,
        *(-value for value in prepare_angles),
    )


def subnormalization_constant() -> float:
    # p(A/alpha) ~= SCALE * (A/alpha)^-1
    #             = SCALE * alpha * A^-1 = A^-1 / beta.
    return 1.0 / (SCALE * ENCODING.alpha)


def workflow_metadata() -> dict:
    return {
        "source": "CUDA-Q Algorithms official matrix-inversion example",
        "epsilon": EPSILON,
        "x_min": X_MIN,
        "degree": 2 * DEGREE_HALF - 1,
        "phase_count": len(PHASES),
        "inverse_scale": SCALE,
        "block_encoding_alpha": ENCODING.alpha,
        "recovery": "remove QSP global phase and take real good-subspace part",
    }
