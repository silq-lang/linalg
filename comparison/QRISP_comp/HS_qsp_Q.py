RHO = -np.pi


def build_program():
    operand = QuantumFloat(2)
    ry(np.pi / 7, operand[0])
    ry(np.pi / 9, operand[1])
    block_encoding = build_tfim()
    ancillas = block_encoding.create_ancillas()
    flag = QuantumBool()

    def walk():
        qubitized_walk(block_encoding, ancillas, operand)

    apply_plain_gqsp(flag, walk, THETA, PHI, RHO, k=14)
    return operand, (flag, *ancillas)


if __name__ == "__main__":
    print(build_program()[0].qs.to_qasm3())
